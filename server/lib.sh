#!/usr/bin/env bash
# Iraq Game Route X1 relay helper. No secrets are emitted to stdout.
set -Eeuo pipefail

IGRX_DIR="${IGRX_DIR:-/etc/igrx1}"
IGRX_IF="${IGRX_IF:-igrx1}"
IGRX_WG_DIR="${IGRX_WG_DIR:-/etc/wireguard}"
IGRX_CONF="$IGRX_WG_DIR/$IGRX_IF.conf"

fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
require_root() { [[ ${EUID:-$(id -u)} -eq 0 ]] || fail 'Run as root (sudo).'; }
require_command() { command -v "$1" >/dev/null 2>&1 || fail "Missing command: $1"; }

validate_host() {
    local host="$1" label
    [[ ${#host} -ge 1 && ${#host} -le 253 ]] || return 1
    # IPv4 or ASCII DNS hostname; no shell metacharacters and no whitespace.
    [[ "$host" =~ ^[A-Za-z0-9][A-Za-z0-9.-]*$ ]] || return 1
    [[ "$host" != *..* ]] || return 1
    local IFS='.'
    read -r -a labels <<< "$host"
    for label in "${labels[@]}"; do
        [[ -n "$label" && ${#label} -le 63 && "$label" != -* && "$label" != *- ]] || return 1
    done
    # Reject malformed numeric IPv4 candidates.
    if [[ "$host" =~ ^[0-9.]+$ ]]; then
        [[ ${#labels[@]} -eq 4 ]] || return 1
        for label in "${labels[@]}"; do
            [[ "$label" =~ ^[0-9]{1,3}$ ]] || return 1
            (( 10#$label <= 255 )) || return 1
        done
    fi
}
# The endpoint used by a publicly reachable relay must not be a private,
# loopback, link-local, test/documentation, or multicast literal IPv4 address.
# Hostnames are syntactically validated here; provider/DNS reachability is
# checked at deployment time, not guessed from the name.
validate_public_endpoint() {
    local host="$1" a b c d
    validate_host "$host" || return 1
    [[ "$host" =~ ^[0-9.]+$ ]] || return 0
    IFS=. read -r a b c d <<< "$host"
    a=$((10#$a)); b=$((10#$b)); c=$((10#$c)); d=$((10#$d))
    (( a >= 1 && a <= 223 )) || return 1
    (( a != 10 && a != 127 )) || return 1
    (( !(a == 100 && b >= 64 && b <= 127) )) || return 1
    (( !(a == 169 && b == 254) )) || return 1
    (( !(a == 172 && b >= 16 && b <= 31) )) || return 1
    (( !(a == 192 && (b == 0 || b == 168)) )) || return 1
    (( !(a == 198 && (b == 18 || b == 19 || (b == 51 && c == 100))) )) || return 1
    (( !(a == 203 && b == 0 && c == 113) )) || return 1
    return 0
}
validate_interface() { [[ "$1" =~ ^[a-zA-Z][a-zA-Z0-9_.-]{0,14}$ ]]; }
validate_region() { [[ "$1" =~ ^[a-z][a-z0-9-]{1,31}$ ]]; }
validate_name() { [[ "$1" =~ ^[a-zA-Z][a-zA-Z0-9_-]{0,31}$ ]]; }
validate_port() { [[ "$1" =~ ^[0-9]{4,5}$ ]] && (( 10#$1 >= 1024 && 10#$1 <= 65535 )); }
validate_prefix() {
    [[ "$1" =~ ^10\.([0-9]{1,3})\.([0-9]{1,3})$ ]] || return 1
    local a="${BASH_REMATCH[1]}" b="${BASH_REMATCH[2]}"
    (( 10#$a <= 255 && 10#$b <= 255 ))
}
lock_state() {
    mkdir -p "$IGRX_DIR"
    chmod 700 "$IGRX_DIR"
    require_command flock
    exec 9>"$IGRX_DIR/.lock"
    flock -x 9
}
load_metadata() {
    [[ -r "$IGRX_DIR/relay.env" ]] || fail 'Relay not installed. Run install-relay.sh first.'
    # Only root can write this file, generated by our installer with shell-quoted values.
    # shellcheck disable=SC1091
    source "$IGRX_DIR/relay.env"
    validate_host "$PUBLIC_ENDPOINT" || fail 'Invalid saved endpoint.'
    validate_port "$WG_PORT" || fail 'Invalid saved UDP port.'
    validate_prefix "$WG_PREFIX" || fail 'Invalid saved subnet.'
}
